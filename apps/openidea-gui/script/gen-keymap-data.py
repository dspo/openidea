#!/usr/bin/env python3
"""Generates src/keymap_data.rs from the upstream Tauri frontend's keymap presets.

The preset data (action id -> default keystrokes) is factual data ported from
`src/platform/keymaps/*.ts` of this repository's own frontend; per the fork's
clean-room rules only the data moves, never the implementation. Re-run after
every upstream sync so the app's table tracks the presets:

    python3 script/gen-keymap-data.py
"""

import re
import sys
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = APP_DIR.parent.parent
SRC = REPO_ROOT / "src" / "platform" / "keymaps"

# name in the generated Rust table -> (source file, exported const)
PRESETS = {
    "INTELLIJ_MACOS": ("intellij-macos.ts", "intellijMacos"),
    "INTELLIJ_WINDOWS": ("intellij-windows.ts", "intellijWindows"),
    "VSCODE_MACOS": ("vscode-macos.ts", "vscodeMacos"),
    "VSCODE_WINDOWS": ("vscode-windows.ts", "vscodeWindows"),
}

ENTRY_HEAD_RE = re.compile(r'"([A-Za-z0-9_.]+)"\s*:\s*\[')


def scan_string(body: str, start: int) -> tuple[str, int]:
    """Scans one double-quoted TS string starting at `start` (the open quote);
    returns (value, index after the close quote)."""
    buf = []
    i = start + 1
    while i < len(body):
        ch = body[i]
        if ch == "\\":
            buf.append(body[i + 1])
            i += 2
            continue
        if ch == '"':
            return "".join(buf), i + 1
        buf.append(ch)
        i += 1
    raise ValueError("unterminated string")


def parse_preset(path: Path, const: str) -> list[tuple[str, list[str]]]:
    text = path.read_text(encoding="utf-8")
    start = text.index(f"const {const}")
    body = text[start : text.index("\n};", start)]
    rows: list[tuple[str, list[str]]] = []
    pos = 0
    while True:
        head = ENTRY_HEAD_RE.search(body, pos)
        if head is None:
            break
        action = head.group(1)
        i = head.end()  # just past the opening bracket
        keys: list[str] = []
        while True:
            while i < len(body) and body[i] in " \t\r\n,":
                i += 1
            if i >= len(body):
                raise ValueError(f"unterminated key list for {action}")
            if body[i] == "]":
                break
            if body[i] == '"':
                key, i = scan_string(body, i)
                keys.append(key)
            else:
                raise ValueError(f"unexpected {body[i]!r} in keys of {action}")
        rows.append((action, keys))
        pos = i
    return rows


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    out = [line.rstrip() for line in f"""//! GENERATED by script/gen-keymap-data.py — do not edit by hand.
//!
//! Ported as data from the upstream Tauri frontend's keymap presets
//! (`src/platform/keymaps/*.ts` in this repository): the action-id ->
//! default-keystrokes maps are factual data (the clean-room rules allow the
//! data, not the implementation). Re-run the generator after an upstream
//! sync so this table tracks the presets.
//!
//! Keystrokes keep the presets' own notation: Meta/Ctrl/Alt/Shift + key,
//! space-separated steps for two-strike chords, `[]` for unbound.

/// One preset row: the upstream action id and its default keystrokes.
pub struct PresetRow {{
    pub action: &'static str,
    pub keys: &'static [&'static str],
}}

/// One keymap preset.
pub struct Preset {{
    pub name: &'static str,
    pub rows: &'static [PresetRow],
}}
""".splitlines()]

    counts = []
    for table, (filename, const) in PRESETS.items():
        rows = parse_preset(SRC / filename, const)
        counts.append((filename, len(rows)))
        out.append("")
        out.append(f"pub static {table}: Preset = Preset {{")
        out.append(f"    name: {rust_str(const)},")
        out.append("    rows: &[")
        for action, keys in rows:
            keys_src = ", ".join(rust_str(k) for k in keys)
            out.append(f"        PresetRow {{ action: {rust_str(action)}, keys: &[{keys_src}] }},")
        out.append("    ],")
        out.append("};")
    out.append("")

    target = APP_DIR / "src" / "keymap_data.rs"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    for filename, count in counts:
        print(f"{filename}: {count} rows")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
